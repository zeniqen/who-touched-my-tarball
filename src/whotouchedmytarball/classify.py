"""Explain each raw difference and decide how risky it is.

The classifier avoids a hard-coded allow list of "safe" files. Instead it explains differences
using evidence from the package itself:

* the source repository (a pattern that also exists in the source was probably compiled from it),
* the previous release of the same package (a file or pattern that was already shipped before),
* the packaging format (metadata files every sdist, wheel or npm tarball contains).

Content is scanned even when a difference has a benign explanation, because build output is
exactly where supply-chain attacks hide.
"""

from __future__ import annotations

import configparser
import json
import re
from dataclasses import dataclass, field
from pathlib import Path, PurePosixPath

from .compare import RawDiff, decode_text
from .models import Category, DiffKind, Finding, Severity, Signal
from .signals import combo_signal, is_code_path, scan_lines

BUILD_DIRS = {
    "dist", "build", "lib", "es", "esm", "cjs", "umd", "out", "bundle", "bundles", "compiled",
    "types", "typings", "_cjs", "_esm", "_types", "dist-cjs", "dist-esm", "dist-types",
}
BUILD_SUFFIXES = (".min.js", ".min.mjs", ".min.cjs", ".map", ".d.ts", ".d.mts", ".d.cts", ".pyc", ".pyo")
COMPILED_SUFFIXES = (".so", ".pyd", ".dylib", ".node", ".dll", ".wasm", ".a", ".lib", ".o")
TS_SOURCE_SUFFIXES = (".ts", ".tsx", ".mts", ".cts", ".coffee", ".svelte", ".vue", ".jsx")
JS_OUTPUT_SUFFIXES = (".js", ".mjs", ".cjs")
DOC_SUFFIXES = (".md", ".rst", ".txt", ".markdown", ".adoc", ".html")
DOC_PREFIXES = ("license", "licence", "copying", "notice", "authors", "changelog", "changes", "history",
                "readme", "contributors", "code_of_conduct", "security", "funding")
BLOB_SUFFIXES = (".xz", ".lzma", ".gz", ".bz2", ".zip", ".7z", ".bin", ".dat", ".tar", ".zst")
ASSET_SUFFIXES = (".png", ".jpg", ".jpeg", ".gif", ".svg", ".ico", ".webp", ".woff", ".woff2", ".ttf",
                  ".otf", ".eot", ".mp3", ".wav", ".pdf")
AUTOTOOLS_GENERATED = {"configure", "makefile.in", "aclocal.m4", "config.h.in", "ltmain.sh", "install-sh",
                       "missing", "compile", "depcomp", "config.guess", "config.sub", "test-driver"}
INSTALL_SCRIPT_NAMES = {"install.js", "postinstall.js", "preinstall.js", "setup.js", "install.sh",
                        "postinstall.sh", "preinstall.sh", "bundle.js"}
NPM_INSTALL_HOOKS = ("preinstall", "install", "postinstall", "preuninstall", "uninstall", "postuninstall",
                     "prepublish")
NPM_ENTRY_KEYS = ("main", "module", "bin", "exports", "browser", "types", "typings")
NPM_DEP_KEYS = ("dependencies", "optionalDependencies", "peerDependencies", "bundleDependencies",
                "bundledDependencies")
VERSION_FILE_RE = re.compile(r"^_{0,2}version(_info)?\.(py|js|ts|json|txt)$|^_version\.py$", re.IGNORECASE)
GENERATED_MARKER_RE = re.compile(r"(auto-?generated|generated by|do not edit|@generated)", re.IGNORECASE)
EGG_INFO_SETUP_CFG_RE = re.compile(r"^\s*(\[egg_info\]|tag_build\s*=|tag_date\s*=|tag_svn_revision\s*=)?\s*$")
KNOWN_PTH = re.compile(r"(distutils-precedence\.pth|-nspkg\.pth|_virtualenv\.pth)$")
EXECUTABLE_MAGIC = (b"\x7fELF", b"MZ", b"\xfe\xed\xfa\xce", b"\xfe\xed\xfa\xcf", b"\xcf\xfa\xed\xfe",
                    b"\xce\xfa\xed\xfe", b"\xca\xfe\xba\xbe")


@dataclass
class ClassifyContext:
    ecosystem: str
    source_available: bool
    source_rules: set[str] = field(default_factory=set)
    source_compiled_stems: set[str] = field(default_factory=set)
    source_code_stems: set[str] = field(default_factory=set)  # base names of every code file in the source
    source_manifest: dict | None = None
    previous_version: str | None = None
    previous_files: dict[str, Path] | None = None
    _previous_manifest: dict | None = None

    def previous_has(self, path: str) -> bool:
        return bool(self.previous_files) and path in self.previous_files

    def previous_rules(self, path: str) -> set[str]:
        if not self.previous_files or path not in self.previous_files:
            return set()
        f = self.previous_files[path]
        if f.stat().st_size > 4 * 1024 * 1024:
            return set()
        text = decode_text(f.read_bytes())
        if text is None:
            return set()
        return {s.rule for s in scan_lines(path, list(enumerate(text.splitlines(), start=1)))}

    def previous_manifest(self) -> dict | None:
        if self._previous_manifest is None and self.previous_files and "package.json" in self.previous_files:
            self._previous_manifest = _load_json(self.previous_files["package.json"].read_bytes()) or {}
        return self._previous_manifest


def classify(d: RawDiff, ctx: ClassifyContext) -> Finding:
    path = d.path
    p = PurePosixPath(path)
    name = p.name.lower()
    lower = path.lower()
    kind = DiffKind(d.kind)
    no_source = not ctx.source_available

    finding = Finding(
        path=path,
        kind=kind,
        category=Category.UNEXPLAINED,
        severity=Severity.LOW,
        reason="",
        source_path=d.source_path,
        diff_excerpt=d.diff_excerpt,
        added_lines=len(d.added),
        removed_lines=d.removed_count,
    )

    def done(category: Category, severity: Severity, reason: str, scan: bool = True) -> Finding:
        finding.category = category
        finding.severity = severity
        finding.reason = reason
        if scan:
            _apply_signals(finding, d, ctx)
        return finding

    # 1. Formatting-only differences
    if d.whitespace_only:
        return done(Category.FORMATTING, Severity.INFO, "Only whitespace or line endings differ", scan=False)

    # 2. Packaging metadata produced by every build
    if ctx.ecosystem == "pypi":
        if path == "PKG-INFO" or any(part.endswith((".egg-info", ".dist-info")) for part in p.parts[:-1]):
            return done(Category.PACKAGING_METADATA, Severity.INFO,
                        "Packaging metadata generated by the Python build backend", scan=False)
        if name == "setup.cfg" and kind == DiffKind.MODIFIED and (
            all(EGG_INFO_SETUP_CFG_RE.match(t) for _, t in d.added) or _setup_cfg_equivalent(d)
        ):
            return done(Category.PACKAGING_METADATA, Severity.INFO,
                        "setup.cfg rewritten by setuptools at build time (egg_info tags and formatting only)",
                        scan=False)

    # 3. npm manifest
    if ctx.ecosystem == "npm" and path == "package.json":
        return _classify_package_json(finding, d, ctx)

    # 4. Python manifests
    if ctx.ecosystem == "pypi" and name in ("setup.py", "pyproject.toml", "setup.cfg") and len(p.parts) == 1:
        reason = ("Python build manifest differs from the source repository; setup.py runs at install time"
                  if name == "setup.py" else "Python build manifest differs from the source repository")
        return done(Category.MANIFEST_CHANGE, Severity.LOW if name != "setup.py" else Severity.MEDIUM, reason)

    data = d.package_bytes() if d.package_file.stat().st_size <= 4 * 1024 * 1024 else b""
    is_binary = decode_text(data[:65536]) is None if data else False

    # 5. Python .pth files execute on every interpreter start
    if name.endswith(".pth"):
        text = decode_text(data) or ""
        has_import = any(line.lstrip().startswith("import") for line in text.splitlines())
        if KNOWN_PTH.search(name) and not has_import:
            return done(Category.BUILD_SCRIPT, Severity.LOW, "Path configuration file")
        sev = Severity.HIGH if has_import else Severity.MEDIUM
        return done(Category.BUILD_SCRIPT, sev,
                    ".pth file in the package"
                    + (" with an import line, which executes code every time Python starts" if has_import else ""))

    # 6. Binaries
    if is_binary or lower.endswith(COMPILED_SUFFIXES):
        if lower.endswith(COMPILED_SUFFIXES):
            return done(Category.BUILD_OUTPUT, Severity.LOW,
                        "Compiled binary built at release time; it cannot be compared to source directly",
                        scan=False)
        if data.startswith(EXECUTABLE_MAGIC):
            return done(Category.SUSPICIOUS, Severity.HIGH,
                        "Executable binary with no source counterpart and no compiled-module file extension",
                        scan=False)
        if lower.endswith(BLOB_SUFFIXES):
            sev = Severity.MEDIUM if kind == DiffKind.PACKAGE_ONLY else Severity.HIGH
            return done(Category.UNEXPLAINED, sev,
                        "Opaque compressed/binary blob not in the source repository "
                        "(the XZ backdoor hid its payload in binary test files)", scan=False)
        if lower.endswith(ASSET_SUFFIXES):
            return done(Category.BUILD_OUTPUT, Severity.INFO, "Binary asset (image/font/media)", scan=False)
        return done(Category.UNEXPLAINED, Severity.LOW if kind == DiffKind.PACKAGE_ONLY else Severity.MEDIUM,
                    "Binary file differs from or is missing in the source repository", scan=False)

    # 7. Build and install scripts
    if name in AUTOTOOLS_GENERATED or name.endswith(".m4"):
        if kind == DiffKind.PACKAGE_ONLY:
            return done(Category.BUILD_SCRIPT, Severity.LOW,
                        "Autotools file generated for the release tarball; unverifiable against source "
                        "(the XZ backdoor was injected through a release-only build-to-host.m4)")
        return done(Category.BUILD_SCRIPT, Severity.HIGH,
                    "Build script in the release differs from the one in the source repository "
                    "(this is exactly how the XZ backdoor was delivered)")
    if name in INSTALL_SCRIPT_NAMES or lower.endswith((".sh", ".ps1", ".bat", ".cmd")):
        return done(Category.BUILD_SCRIPT, Severity.MEDIUM,
                    "Install/shell script " + ("only in the package" if kind == DiffKind.PACKAGE_ONLY
                                               else "differs from the source repository"))

    # 8. Generated files
    if VERSION_FILE_RE.match(name) and len(data) < 4096:
        return done(Category.GENERATED, Severity.INFO, "Version file written by the build tooling")
    head = (decode_text(data[:2048]) or "").splitlines()[:6]
    if any(GENERATED_MARKER_RE.search(line) for line in head):
        return done(Category.GENERATED, Severity.LOW, "File declares itself as generated")

    # 9. Documentation. A doc-like name (security.js, history.py) is not enough on its own:
    # code files are always scanned, whatever they are called.
    if lower.endswith(DOC_SUFFIXES) or (name.startswith(DOC_PREFIXES) and not is_code_path(path)):
        return done(Category.DOCUMENTATION, Severity.INFO, "Documentation or license text", scan=False)

    # 10. Build output
    if _is_build_output(path, ctx):
        if kind == DiffKind.MODIFIED:
            return done(Category.BUILD_OUTPUT, Severity.LOW,
                        "Build output committed to the repository differs from the published build")
        reason = "Build output produced at publish time (no direct source counterpart)"
        if ctx.previous_has(path):
            reason += f"; also shipped in {ctx.previous_version}"
        return done(Category.BUILD_OUTPUT, Severity.LOW, reason)

    # 11. A minified build of a readable source file (dayjs: src/locale/de.js -> locale/de.js).
    # Still scanned: anything appended to the minified copy shows up as new signals.
    if kind == DiffKind.MODIFIED and _looks_minified(data) and not _looks_minified(d.source_bytes() or b""):
        return done(Category.BUILD_OUTPUT, Severity.LOW,
                    "Minified build of the source file (the source is readable, the published copy is minified)")

    # 12. Nothing explains it
    if kind == DiffKind.MODIFIED:
        return done(Category.UNEXPLAINED, Severity.MEDIUM,
                    "Content differs from the source repository and no build step explains it")
    if no_source:
        return done(Category.UNEXPLAINED, Severity.INFO, "No source repository available to compare against")
    sev = Severity.MEDIUM if is_code_path(path) else Severity.LOW
    reason = "File is shipped in the package but does not exist in the source repository"
    if ctx.previous_has(path):
        sev = sev.step_down()
        reason += f" (it was also shipped in {ctx.previous_version})"
    elif ctx.previous_files is not None:
        reason += f" and is new since {ctx.previous_version}"
    return done(Category.UNEXPLAINED, sev, reason)


def _is_build_output(path: str, ctx: ClassifyContext) -> bool:
    lower = path.lower()
    parts = PurePosixPath(lower).parts
    if parts and parts[0] in BUILD_DIRS and len(parts) > 1:
        return True
    if lower.endswith(BUILD_SUFFIXES) or "__pycache__" in parts:
        return True
    if lower.endswith(JS_OUTPUT_SUFFIXES):
        stem = PurePosixPath(lower).name.rsplit(".", 1)[0]
        if stem in ctx.source_compiled_stems:
            return True
    return False


def _looks_minified(data: bytes) -> bool:
    text = decode_text(data[:256 * 1024]) or ""
    lines = [line for line in text.splitlines() if line.strip()]
    if not lines:
        return False
    return max(len(line) for line in lines) > 1000 or sum(len(line) for line in lines) / len(lines) > 200


def _apply_signals(finding: Finding, d: RawDiff, ctx: ClassifyContext) -> None:
    if not d.added:
        return
    signals = scan_lines(d.path, d.added)
    if not signals:
        return

    explain_by_source = finding.kind == DiffKind.PACKAGE_ONLY and finding.category in (
        Category.BUILD_OUTPUT, Category.GENERATED, Category.UNEXPLAINED
    )
    source_file_rules: set[str] = set()
    if finding.kind == DiffKind.MODIFIED and d.source_file is not None:
        text = decode_text(d.source_bytes() or b"") or ""
        source_file_rules = {s.rule for s in scan_lines(d.path, list(enumerate(text.splitlines(), start=1)))}
    prev_rules = ctx.previous_rules(d.path) if ctx.previous_has(d.path) else set()

    # Build output is excused fully only when the source has a file it could be compiled from
    # (dist/index.js <- src/index.ts). A new file with no counterpart could have been injected,
    # so a pattern seen elsewhere in the repository only lowers its signals by one level. Those
    # signals stay active, so decoding plus execution in such a file is still CRITICAL.
    has_counterpart = file_stem(d.path) in ctx.source_code_stems
    partly_explained: list[str] = []
    for s in signals:
        if explain_by_source and s.rule in ctx.source_rules and has_counterpart:
            s.explained_by = "the same pattern exists in the source repository (likely compiled from it)"
            s.severity = Severity.INFO
        elif explain_by_source and s.rule in ctx.source_rules:
            s.severity = s.severity.step_down()
            partly_explained.append(s.rule)
        elif s.rule in source_file_rules:
            s.explained_by = "the source version of this file uses the same pattern"
            s.severity = s.severity.step_down()
        elif s.rule in prev_rules:
            s.explained_by = f"already present in the previous release ({ctx.previous_version})"
            s.severity = s.severity.step_down()

    # Bundlers write long lines and dense output, so in build output those two heuristics are weak
    # evidence. They stay active, so together with execution or network access they still combine.
    if finding.category == Category.BUILD_OUTPUT:
        for s in signals:
            if s.rule in ("very-long-line", "high-entropy") and s.explained_by is None:
                s.severity = Severity.LOW
    if partly_explained:
        finding.notes.append(
            "Lowered one level: " + ", ".join(sorted(set(partly_explained)))
            + " also appear elsewhere in the source repository, but no source file matches this file's name"
        )
    combo = combo_signal(signals)
    if combo:
        signals.append(combo)
    finding.signals = signals
    _escalate(finding)


def _escalate(finding: Finding) -> None:
    active = [s for s in finding.signals if s.explained_by is None]
    top = Severity.max(*(s.severity for s in finding.signals)) if finding.signals else Severity.INFO
    finding.severity = Severity.max(finding.severity, top)
    if any(s.severity.rank >= Severity.HIGH.rank for s in active):
        if finding.category != Category.SUSPICIOUS:
            finding.notes.append(f"Originally classified as {finding.category.value}; escalated by content signals")
        finding.category = Category.SUSPICIOUS


def _parse_cfg(data: bytes | None) -> dict | None:
    text = decode_text(data or b"")
    if text is None:
        return None
    parser = configparser.ConfigParser(interpolation=None, strict=False)
    try:
        parser.read_string(text)
    except configparser.Error:
        return None
    return {
        section: {key: [v.strip() for v in value.splitlines() if v.strip()] for key, value in parser[section].items()}
        for section in parser.sections()
        if section != "egg_info"
    }


def _setup_cfg_equivalent(d: RawDiff) -> bool:
    """setuptools re-serializes setup.cfg in sdists; compare the parsed content instead of bytes."""
    pkg, src = _parse_cfg(d.package_bytes()), _parse_cfg(d.source_bytes())
    return pkg is not None and pkg == src


def _load_json(data: bytes) -> dict | None:
    try:
        value = json.loads(data.decode("utf-8"))
    except (UnicodeDecodeError, json.JSONDecodeError):
        return None
    return value if isinstance(value, dict) else None


def _classify_package_json(finding: Finding, d: RawDiff, ctx: ClassifyContext) -> Finding:
    finding.category = Category.MANIFEST_CHANGE
    finding.severity = Severity.INFO
    pkg = _load_json(d.package_bytes())
    src = ctx.source_manifest if ctx.source_manifest is not None else (
        _load_json(d.source_bytes()) if d.source_file else None
    )
    if pkg is None:
        finding.category = Category.UNEXPLAINED
        finding.severity = Severity.MEDIUM
        finding.reason = "package.json in the package is not valid JSON"
        return finding

    signals: list[Signal] = []
    changed: list[str] = []
    src_scripts = (src or {}).get("scripts") or {}
    pkg_scripts = pkg.get("scripts") or {}
    prev = ctx.previous_manifest()
    prev_scripts = (prev or {}).get("scripts") or {}

    for hook in NPM_INSTALL_HOOKS:
        if hook not in pkg_scripts:
            continue
        cmd = str(pkg_scripts[hook])
        if src is not None and src_scripts.get(hook) == pkg_scripts[hook]:
            finding.notes.append(f"Runs `{hook}: {cmd}` at install time (same as the source repository)")
            continue
        if src is None:
            sev = Severity.MEDIUM
            desc = f"Install-time script `{hook}: {cmd}`"
            if prev is not None and hook not in prev_scripts:
                sev = Severity.HIGH
                desc += f" that is new since {ctx.previous_version}"
        else:
            sev = Severity.HIGH
            desc = f"Install-time script `{hook}: {cmd}` is not in the source repository's package.json"
        signals.append(Signal(rule="npm-install-hook", description=desc, severity=sev, snippet=cmd[:200]))

    if src is not None:
        for key in NPM_ENTRY_KEYS:
            if key in pkg and pkg.get(key) != src.get(key):
                signals.append(Signal(
                    rule="npm-entry-point-changed",
                    description=f"`{key}` differs from the source repository: {json.dumps(src.get(key))} -> "
                    f"{json.dumps(pkg.get(key))}",
                    severity=Severity.MEDIUM,
                ))
        for key in NPM_DEP_KEYS:
            pkg_deps = pkg.get(key) or {}
            src_deps = src.get(key) or {}
            if not isinstance(pkg_deps, dict) or not isinstance(src_deps, dict):
                continue
            for dep in sorted(set(pkg_deps) - set(src_deps)):
                signals.append(Signal(
                    rule="npm-dependency-added",
                    description=f"{key} `{dep}@{pkg_deps[dep]}` is not declared in the source repository",
                    severity=Severity.MEDIUM,
                ))
            for dep in sorted(set(pkg_deps) & set(src_deps)):
                if pkg_deps[dep] != src_deps[dep]:
                    changed.append(f"{key}.{dep}: {src_deps[dep]} -> {pkg_deps[dep]}")
        for key in sorted(set(pkg) | set(src)):
            if key in ("scripts", *NPM_ENTRY_KEYS, *NPM_DEP_KEYS):
                continue
            if pkg.get(key) != src.get(key):
                changed.append(key)

    if changed:
        finding.notes.append("Other fields that differ: " + ", ".join(changed[:15]))
    finding.signals = signals
    if signals:
        finding.reason = "package.json differs from the source repository in security-relevant fields"
    elif d.kind == DiffKind.MODIFIED:
        finding.reason = "package.json differs only in non-executable metadata (version, publish fields)"
    else:
        finding.reason = "package.json (no source manifest to compare against)"
    _escalate(finding)
    return finding


def file_stem(path: str) -> str:
    """Base name up to the first dot, so dist/Ky.d.ts, Ky.js.map and src/ky.ts all give "ky"."""
    return PurePosixPath(path.lower()).name.split(".", 1)[0]


def code_stems(source_files: dict[str, Path]) -> set[str]:
    return {file_stem(rel) for rel in source_files if is_code_path(rel)}


def collect_source_context(source_files: dict[str, Path], prefix: str) -> tuple[set[str], set[str]]:
    """Scan the source tree once to learn which patterns and compiled-file stems are normal for it."""
    rules: set[str] = set()
    stems: set[str] = set()
    scanned_bytes = 0
    for rel, f in source_files.items():
        lower = rel.lower()
        if lower.endswith(TS_SOURCE_SUFFIXES) and not lower.endswith((".d.ts", ".d.mts", ".d.cts")):
            stems.add(PurePosixPath(lower).name.rsplit(".", 1)[0])
        if not is_code_path(rel) or scanned_bytes > 200 * 1024 * 1024:
            continue
        try:
            size = f.stat().st_size
        except OSError:
            continue
        if size > 2 * 1024 * 1024:
            continue
        scanned_bytes += size
        text = decode_text(f.read_bytes())
        if text is None:
            continue
        rules |= {s.rule for s in scan_lines(rel, list(enumerate(text.splitlines(), start=1)))}
    return rules, stems
